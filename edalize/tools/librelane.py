import json
import os.path

from edalize.tools.edatool import Edatool
from edalize.utils import EdaCommands

# LibreLane writes each run to runs/<tag>. A fixed tag gives the final views a
# predictable path that can be used as a make target.
RUN_TAG = "edalize"
CONFIG_FILE = "config.json"


class Librelane(Edatool):

    description = "LibreLane RTL-to-GDSII ASIC implementation flow"

    TOOL_OPTIONS = {
        "pdk": {
            "type": "str",
            "desc": "PDK, e.g. sky130A, gf180mcuD or ihp-sg13g2 (LibreLane defaults to sky130A)",
        },
        "scl": {
            "type": "str",
            "desc": "Standard cell library (LibreLane defaults to the PDK's default library)",
        },
        "librelane_flow": {
            "type": "str",
            "desc": "LibreLane flow, e.g. Classic, VHDLClassic or Chip (LibreLane defaults to Classic)",
        },
        "librelane_config": {
            "type": "str",
            "desc": "Extra configuration variables as KEY=VALUE, e.g. CLOCK_PORT=clk. VALUE is parsed as JSON if possible, otherwise used as a string. Overrides variables generated by Edalize",
            "list": True,
        },
        "librelane_options": {
            "type": "str",
            "desc": "Additional options for librelane. Placed first on the command line so that --dockerized can be used",
            "list": True,
        },
    }

    @staticmethod
    def _librelane_path(path):
        # Relative EDAM paths are relative to work_root, which is also the
        # LibreLane design directory since config.json is written there.
        # LibreLane resolves dir:: against the design directory.
        return path if os.path.isabs(path) else "dir::" + path

    def setup(self, edam):
        super().setup(edam)

        verilog_files = []
        vhdl_files = []
        sdc_files = []
        incdirs = []
        depfiles = []
        for f in self.files:
            name = f["name"]
            file_type = f.get("file_type", "")
            if file_type.startswith(("verilogSource", "systemVerilogSource")):
                if not self._add_include_dir(f, incdirs):
                    verilog_files.append(name)
            elif file_type.startswith("vhdlSource"):
                vhdl_files.append(name)
            elif file_type == "SDC":
                sdc_files.append(name)
            else:
                continue
            # Rerun LibreLane when any file it reads changes
            depfiles.append(name)

        if len(sdc_files) > 1:
            raise RuntimeError(
                "LibreLane only supports one SDC file. Found " + " and ".join(sdc_files)
            )

        config = {"DESIGN_NAME": self.toplevel}
        if verilog_files:
            config["VERILOG_FILES"] = [self._librelane_path(f) for f in verilog_files]
        if vhdl_files:
            config["VHDL_FILES"] = [self._librelane_path(f) for f in vhdl_files]
        if incdirs:
            config["VERILOG_INCLUDE_DIRS"] = [self._librelane_path(d) for d in incdirs]
        if self.vlogdefine:
            config["VERILOG_DEFINES"] = [
                "{}={}".format(k, self._param_value_str(v))
                for k, v in self.vlogdefine.items()
            ]
        if self.vlogparam:
            # LibreLane passes these to Yosys chparam, which expects Verilog
            # constants, so string values need quotes
            config["SYNTH_PARAMETERS"] = [
                "{}={}".format(k, self._param_value_str(v, str_quote_style='"'))
                for k, v in self.vlogparam.items()
            ]
        if sdc_files:
            sdc_file = self._librelane_path(sdc_files[0])
            config["PNR_SDC_FILE"] = sdc_file
            config["SIGNOFF_SDC_FILE"] = sdc_file

        # User-supplied variables take precedence over generated ones
        for entry in self.tool_options.get("librelane_config", []):
            key, sep, value = entry.partition("=")
            if not sep:
                raise RuntimeError(
                    f"librelane_config entry '{entry}' must be on the form KEY=VALUE"
                )
            try:
                # Numbers, booleans, lists and dicts, e.g. CLOCK_PERIOD=20
                value = json.loads(value)
            except json.JSONDecodeError:
                # Plain strings, e.g. CLOCK_PORT=clk
                pass
            config[key] = value
        self.config = config

        gds_file = f"runs/{RUN_TAG}/final/gds/{self.toplevel}.gds"

        # User options go first since --dockerized only forwards the arguments
        # after it into the container
        command = ["librelane"] + self.tool_options.get("librelane_options", [])
        command += ["--run-tag", RUN_TAG, "--overwrite"]
        for option, flag in [
            ("pdk", "--pdk"),
            ("scl", "--scl"),
            ("librelane_flow", "--flow"),
        ]:
            if option in self.tool_options:
                command += [flag, self.tool_options[option]]
        command.append(CONFIG_FILE)

        commands = EdaCommands()
        commands.add(command, [gds_file], [CONFIG_FILE] + depfiles)
        commands.set_default_target(gds_file)
        self.commands = commands

    def write_config_files(self):
        self.update_config_file(CONFIG_FILE, json.dumps(self.config, indent=2) + "\n")
